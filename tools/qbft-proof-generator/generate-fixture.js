function buildHeaderRlpFromBlock(block) {
  const fields = [
    hexToBuf(block.parentHash),
    hexToBuf(block.sha3Uncles),
    hexToBuf(block.miner),
    hexToBuf(block.stateRoot),
    hexToBuf(block.transactionsRoot),
    hexToBuf(block.receiptsRoot),
    hexToBuf(block.logsBloom),
    hexToTrimmedBuf(block.difficulty),
    hexToTrimmedBuf(block.number),
    hexToTrimmedBuf(block.gasLimit),
    hexToTrimmedBuf(block.gasUsed),
    hexToTrimmedBuf(block.timestamp),
    hexToBuf(block.extraData),
    hexToBuf(block.mixHash),
    hexToBuf(block.nonce),
  ];
  if (block.baseFeePerGas != null) fields.push(hexToTrimmedBuf(block.baseFeePerGas));
  if (block.withdrawalsRoot != null) fields.push(hexToBuf(block.withdrawalsRoot));
  if (block.blobGasUsed != null) {
    fields.push(hexToTrimmedBuf(block.blobGasUsed));
    fields.push(hexToTrimmedBuf(block.excessBlobGas));
  }
  if (block.parentBeaconBlockRoot != null) fields.push(hexToBuf(block.parentBeaconBlockRoot));
  if (block.requestsHash != null) fields.push(hexToBuf(block.requestsHash));
  return rlpEncode(fields);
}

