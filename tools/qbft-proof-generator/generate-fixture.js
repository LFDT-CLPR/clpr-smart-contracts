#!/usr/bin/env node
/**
 * generate-fixture.js
 *
 * Generates a real Besu QBFT bundle-proof fixture for the header-mode QBFT verifier,
 * sourced from a deployed
 * `ClprService` with a populated `Channel` (via `QbftFixtureSetup.s.sol`).
 *
 * Steps:
 *   1. Start a 3-validator QBFT Besu cluster via docker-compose in this directory.
 *      All three nodes form a consensus quorum so each block carries ≥ 2 committed
 *      seals (2f+1 for f=1). Every header lists the 3 validators in `extraData`.
 *   2. Run `forge script QbftFixtureSetup.s.sol --broadcast` to deploy the full
 *      `ClprService` dependency graph, configure it, and walk a channel through
 *      `registerChannel` + `completeChannel`. Parse stdout for the deployed
 *      service address, the populated channelId, and supporting addresses.
 *   3. Derive the storage trie keys the verifier expects from the populated
 *      channel's struct slots (per `_channels[id]` storage layout at root
 *      slot 15) above `keccak256(abi.encode(channelId, 15))`.
 *   4. Call `eth_getProof` for those keys, fetch `debug_getRawHeader`, and pack
 *      everything into the 5-item RLP payload the verifier expects:
 *      field 1 = [validators listed by the header, []].
 *   5. Write fixture files into `test/verifiers/evm/qbft/fixtures/`, including a
 *      6-field header-mode config proof whose header is
 *      the block before the bundle block, so the bundle block is after the anchor.
 *   6. Tear down the Besu cluster.
 *
 * Prerequisites: Docker, Node.js 22+, Foundry (forge, cast).
 * Usage: node generate-fixture.js
 */

import { RLP } from "@ethereumjs/rlp";
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(__dirname, "..", "..");
const FIXTURES_DIR = join(PROJECT_ROOT, "test", "verifiers", "evm", "qbft", "fixtures");

const RPC = "http://127.0.0.1:18545";

// Anvil account 0 — funded in the Besu QBFT genesis; also one of the three validators.
// The verifier itself takes the validator set from each header's extraData, not from here.
const DEPLOYER_PRIVATE_KEY = "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80";
const VALIDATOR_ADDRESS = "0xf39fd6e51aad88f6f4ce6ab8827279cfffb92266";

// `_channels` lives at root slot 15 of `ClprService`. Authoritative source:
// storage-layout.json (regenerated by `forge build`), mirrored by
// `ClprEvmBundleVerifier.CHANNELS_BASE_SLOT`.
const CHANNELS_SLOT = 15;

// `_messageQueues` lives at root slot 1. Within MessageValue, runningHashAfterProcessing
// is at struct offset +1 (payload is offset 0).
const MESSAGE_QUEUES_SLOT = 1;
const MESSAGE_RUNNING_HASH_OFFSET = 1n;

// `Channel` struct offsets the verifier proves (`ClprEvmBundleVerifier._channelMetadataSlots`).
// The verifier derives every slot key from the channelId in its ChannelContext and looks each
// proof entry up by key, so the order is not significant, but every listed slot must be present.
//   struct slot+1:  verifier|status|nextMessageId (packed)
//   struct slot+2:  ackedMessageId|receivedMessageId|nextExpectedReplyId (packed)
//   struct slot+4:  sentRunningHash
//   struct slot+5:  receivedRunningHash
//   struct slot+16: endpointManifestVersion
//   6th entry:      lastMessage.runningHashAfterProcessing (_messageQueues mapping; only with messages)
const PROVEN_STRUCT_OFFSETS = [1n, 2n, 4n, 5n, 16n];

// ─────────────────────────────────────────────────────────────────────────────
// RLP encoding (via @ethereumjs/rlp)
// ─────────────────────────────────────────────────────────────────────────────

/// RLP-encode a (possibly nested) structure of byte buffers and lists.
function rlpEncode(input) {
  return Buffer.from(RLP.encode(input));
}

/// Decode an already-encoded RLP byte string so it can be spliced into a larger list
/// as a nested list (rather than re-wrapped as a byte string).
function rlpDecode(input) {
  return RLP.decode(input);
}

function castKeccak(hexInput) {
  const out = execSync(`cast keccak ${hexInput}`, { encoding: "utf-8" }).trim();
  return out.startsWith("0x") ? out.slice(2) : out;
}

// Derive the storage slot for _messageQueues[channelId][messageId].runningHashAfterProcessing.
// outer = keccak256(abi.encode(channelId, MESSAGE_QUEUES_SLOT))
// inner = keccak256(abi.encode(messageId, outer))
// slot  = inner + MESSAGE_RUNNING_HASH_OFFSET
function deriveMessageRunningHashSlot(channelIdHex, messageId) {
  const idHex = channelIdHex.startsWith("0x") ? channelIdHex.slice(2) : channelIdHex;
  const mqSlotHex = BigInt(MESSAGE_QUEUES_SLOT).toString(16).padStart(64, "0");
  const outer = BigInt("0x" + castKeccak("0x" + idHex + mqSlotHex));
  const msgIdHex = messageId.toString(16).padStart(64, "0");
  const outerHex = outer.toString(16).padStart(64, "0");
  const inner = BigInt("0x" + castKeccak("0x" + msgIdHex + outerHex));
  const slot = (inner + MESSAGE_RUNNING_HASH_OFFSET) & ((1n << 256n) - 1n);
  return "0x" + slot.toString(16).padStart(64, "0");
}

function deriveSlotKey(channelIdHex, structOffset) {
  const idHex = channelIdHex.startsWith("0x") ? channelIdHex.slice(2) : channelIdHex;
  if (idHex.length !== 64) throw new Error(`channelId must be 32 bytes (64 hex), got ${idHex.length}`);

  // abi.encode(bytes32, uint256) = 64 bytes (each left-padded).
  const slotHex = BigInt(CHANNELS_SLOT).toString(16).padStart(64, "0");
  const baseSlot = castKeccak("0x" + idHex + slotHex);

  // structSlot = baseSlot + structOffset (mod 2^256, but offsets are tiny here).
  const structSlotBig = (BigInt("0x" + baseSlot) + structOffset) & ((1n << 256n) - 1n);
  return "0x" + structSlotBig.toString(16).padStart(64, "0");
}

// ─────────────────────────────────────────────────────────────────────────────
// JSON-RPC helper
// ─────────────────────────────────────────────────────────────────────────────

let rpcId = 0;
// Host ports of the three validators (docker-compose.yml). Votes must be cast on a majority of
// validators, so the rotation step talks to node0 and node1 directly.
const NODE_RPCS = ["http://127.0.0.1:18545", "http://127.0.0.1:18546", "http://127.0.0.1:18547"];

async function rpcAt(url, method, params = []) {
  const body = JSON.stringify({ jsonrpc: "2.0", method, params, id: ++rpcId });
  const res = await fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body });
  const json = await res.json();
  if (json.error) throw new Error(`RPC ${method} @ ${url}: ${JSON.stringify(json.error)}`);
  return json.result;
}

async function rpc(method, params = []) {
  const body = JSON.stringify({ jsonrpc: "2.0", method, params, id: ++rpcId });
  const res = await fetch(RPC, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body,
  });
  const json = await res.json();
  if (json.error) throw new Error(`RPC ${method}: ${JSON.stringify(json.error)}`);
  return json.result;
}

async function waitForRpc(maxWait = 60_000) {
  const start = Date.now();
  while (Date.now() - start < maxWait) {
    try {
      await rpc("eth_chainId");
      return;
    } catch {
      await new Promise((r) => setTimeout(r, 500));
    }
  }
  throw new Error("Besu RPC not ready after " + maxWait + "ms");
}

function shell(cmd, opts = {}) {
  return execSync(cmd, { encoding: "utf-8", ...opts }).trim();
}

// ─────────────────────────────────────────────────────────────────────────────
// Header-mode config proof + trust anchor
// ─────────────────────────────────────────────────────────────────────────────

// Throttle values the bootstrap and the final config proof share.
const THROTTLES = [100n, 100_000n, 1_000_000n, 1_000n, 100_000n];

/// The validator list a header carries in extraData item 1 (of [vanity, validators[], vote, round, seals[]]).
function headerValidators(headerRlpBuf) {
  const header = rlpDecode(headerRlpBuf);
  const extra = rlpDecode(header[12]);
  return extra[1].map((v) => Buffer.from(v));
}

function setCommitment(validators) {
  const sorted = [...new Set(validators.map((v) => v.toString("hex")))].sort((a, b) =>
    BigInt("0x" + a) < BigInt("0x" + b) ? -1 : BigInt("0x" + a) > BigInt("0x" + b) ? 1 : 0
  );
  const word = (hex) => hex.padStart(64, "0");
  const encoded = word("20") + word(sorted.length.toString(16)) + sorted.map(word).join("");
  return hexToBuf(castKeccak("0x" + encoded));
}

/// The 128-byte anchor the verifier stores:
/// abi.encode(uint8 mode = 0, bytes32 setCommitment, bytes32 codeHash, uint64 anchorBlockNumber).
function buildTrustAnchor(validators, codeHashBuf, blockNumber) {
  const word = (buf) => Buffer.concat([Buffer.alloc(32 - buf.length, 0), buf]);
  return Buffer.concat([
    word(Buffer.alloc(0)),                         // mode 0 = header mode
    setCommitment(validators),
    word(codeHashBuf),
    word(hexToTrimmedBuf("0x" + BigInt(blockNumber).toString(16))),
  ]);
}

function buildConfigProof(headerRlpBuf, serviceAddrBuf, codeHashBuf) {
  const descriptor = rlpEncode([
    Buffer.alloc(0),                                // 0 mode 0 = header mode (scalar 0 encodes as empty)
    codeHashBuf,                                    // 1 codeHash of the peer service
  ]);
  return rlpEncode([
    serviceAddrBuf,                                 // 0 service address
    Buffer.from("eip155:1"),                        // 1 chainId
    Buffer.alloc(0),                                // 2 peerConfigNanos (0)
    THROTTLES.map((v) => hexToTrimmedBuf("0x" + v.toString(16))), // 3 throttles
    descriptor,                                     // 4 trust anchor descriptor (byte string wrapping an RLP list)
    rlpDecode(headerRlpBuf),                        // 5 block header (raw RLP list spliced as a nested list)
  ]);
}

async function writeBootstrapConfigProof() {
  console.log("Bootstrap: writing configProof.hex from current block so the Forge script can proceed...");
  // Wait for at least one QBFT block so the header carries committed seals.
  let blockNum = await rpc("eth_blockNumber");
  while (BigInt(blockNum) === 0n) {
    await new Promise((r) => setTimeout(r, 500));
    blockNum = await rpc("eth_blockNumber");
  }
  const rawHeaderHex = await rpc("debug_getRawHeader", [blockNum]);
  const headerRlp = hexToBuf(rawHeaderHex);
  const configProof = buildConfigProof(headerRlp, Buffer.alloc(20, 0), Buffer.alloc(32, 0));
  writeFileSync(join(FIXTURES_DIR, "configProof.hex"), configProof.toString("hex") + "\n");
  console.log(`   Written bootstrap configProof.hex (${configProof.length} bytes, block ${blockNum})\n`);
}

// ─────────────────────────────────────────────────────────────────────────────
// Bundle content protobuf
// ─────────────────────────────────────────────────────────────────────────────

// `ClprBundleContent`: field 2 (LEN) = repeated ClprMessagePayload. Inner = the
// raw payload bytes; the wire-level wrap is `0x12 <varint length> <payload>`.
// Bundle content is built dynamically from the real message emitted by the Forge
// script after sendMessage is called.  See buildBundleContent() below.

// ─────────────────────────────────────────────────────────────────────────────
// Hex helpers
// ─────────────────────────────────────────────────────────────────────────────

function hexToBuf(hex) {
  if (!hex) return Buffer.alloc(0);
  const h = hex.startsWith("0x") ? hex.slice(2) : hex;
  if (h.length === 0) return Buffer.alloc(0);
  return Buffer.from(h.length % 2 ? "0" + h : h, "hex");
}

function hexToTrimmedBuf(hex) {
  if (!hex || hex === "0x0" || hex === "0x") return Buffer.alloc(0);
  let h = hex.startsWith("0x") ? hex.slice(2) : hex;
  h = h.replace(/^0+/, "");
  if (h.length === 0) return Buffer.alloc(0);
  if (h.length % 2) h = "0" + h;
  return Buffer.from(h, "hex");
}

// ─────────────────────────────────────────────────────────────────────────────
// Forge script invocation + stdout parsing
// ─────────────────────────────────────────────────────────────────────────────

function runFixtureSetupScript() {
  console.log("   forge script: deploying ClprService + completing channel...");
  const cmd = [
    "forge", "script",
    "tools/qbft-proof-generator/QbftFixtureSetup.s.sol:QbftFixtureSetup",
    "--rpc-url", RPC,
    "--broadcast",
    "--slow", // serialize tx submission — Besu's tx pool is fussy under load
    "--via-ir",
    "-vvv",
  ].join(" ");

  const stdout = shell(cmd, {
    cwd: PROJECT_ROOT,
    env: { ...process.env, PRIVATE_KEY: DEPLOYER_PRIVATE_KEY },
    maxBuffer: 64 * 1024 * 1024,
  });

  // Pull the FIXTURE_OUT::KEY lines out of the script log. forge prefixes each
  // line with whitespace inside the "== Logs ==" section.
  const out = {};
  for (const line of stdout.split("\n")) {
    const m = line.match(/FIXTURE_OUT::([A-Z_0-9]+)\s+(.+?)\s*$/);
    if (m) out[m[1]] = m[2].trim();
  }
  for (const k of ["CLPR_SERVICE", "QBFT_VERIFIER", "CHANNEL_ID", "PEER_SIGNER", "DEPLOYER", "VALIDATOR", "MSG1_PAYLOAD"]) {
    if (!out[k]) {
      console.error("forge script stdout follows:\n" + stdout);
      throw new Error(`forge script did not emit FIXTURE_OUT::${k}`);
    }
  }
  // CHANNEL_ID is logged as a uint256 (decimal). Normalise to a 32-byte hex.
  const channelIdBig = BigInt(out.CHANNEL_ID);
  out.CHANNEL_ID = "0x" + channelIdBig.toString(16).padStart(64, "0");
  return out;
}

// ─────────────────────────────────────────────────────────────────────────────
// Main
// ─────────────────────────────────────────────────────────────────────────────

async function main() {
  console.log("=== Besu QBFT Fixture Generator ===\n");

  // 1. Start Besu cluster.
  console.log("1. Starting Besu QBFT cluster...");
  try { execSync("docker compose down -v 2>/dev/null || true", { cwd: __dirname, stdio: "pipe" }); } catch { }
  execSync("docker compose up -d", { cwd: __dirname, stdio: "inherit" });

  try {
    await waitForRpc(60_000);
    console.log("   Besu is ready.\n");

    // 1b. Bootstrap: write a valid configProof.hex before the Forge script needs it.
    await writeBootstrapConfigProof();

    // 2. Deploy ClprService + complete a channel via the Foundry script.
    console.log("2. Provisioning ClprService and a completed Channel...");
    const provisioned = runFixtureSetupScript();
    const contractAddress = provisioned.CLPR_SERVICE.toLowerCase();
    const verifierAddr = provisioned.QBFT_VERIFIER.toLowerCase();
    const channelId = provisioned.CHANNEL_ID.toLowerCase();
    const validator = provisioned.VALIDATOR.toLowerCase();
    console.log(`   ClprService:     ${contractAddress}`);
    console.log(`   QBFTVerifier:    ${verifierAddr}`);
    console.log(`   ChannelId:    ${channelId}`);
    console.log(`   Validator:       ${validator}\n`);

    // 3. Derive storage trie keys:
    //    entries 0-4 = Channel struct offsets +1, +2, +4, +5, +16
    //    entry  5    = lastMessage.runningHashAfterProcessing (messageId = nextMessageId - 1)
    console.log("3. Deriving storage-slot indices for the proven fields...");
    // After sendMessage, nextMessageId == 2, so lastMessageId == 1.
    const lastMessageId = 1n;
    const msgRunningHashSlot = deriveMessageRunningHashSlot(channelId, lastMessageId);
    console.log(`   lastMessage(id=${lastMessageId}) runningHashAfterProcessing → ${msgRunningHashSlot}`);
    const channelSlots = PROVEN_STRUCT_OFFSETS.map((off) => deriveSlotKey(channelId, off));
    for (let i = 0; i < channelSlots.length; i++) {
      console.log(`   struct slot+${PROVEN_STRUCT_OFFSETS[i]} → storage index ${channelSlots[i]}`);
    }
    const storageKeys = [...channelSlots, msgRunningHashSlot];
    console.log();

    // 4. Fetch eth_getProof.
    console.log("4. Fetching eth_getProof...");
    let proofBlock = await rpc("eth_blockNumber");
    let proof = await rpc("eth_getProof", [contractAddress, storageKeys, proofBlock]);
    console.log(`   Account proof nodes: ${proof.accountProof.length}`);
    console.log(`   Storage proofs:      ${proof.storageProof.length}`);
    for (let i = 0; i < proof.storageProof.length; i++) {
      console.log(`     [${i}] key=${proof.storageProof[i].key} value=${proof.storageProof[i].value} proofNodes=${proof.storageProof[i].proof.length}`);
    }
    console.log(`   Storage root: ${proof.storageHash}`);
    console.log(`   Code hash:    ${proof.codeHash}\n`);

    // 5. Fetch raw header.
    console.log("5. Fetching block header...");
    let rawHeaderHex;
    try {
      rawHeaderHex = await rpc("debug_getRawHeader", [proofBlock]);
      console.log(`   debug_getRawHeader OK (${(rawHeaderHex.length - 2) / 2} bytes)`);
    } catch (e) {
      console.log("   debug_getRawHeader failed: " + e.message);
      console.log("   Falling back to JSON-built header (WARNING: may lack QBFT committed seals!)");
      rawHeaderHex = null;
    }

    const block = await rpc("eth_getBlockByNumber", [proofBlock, false]);
    console.log(`   Block hash:  ${block.hash}`);
    console.log(`   State root:  ${block.stateRoot}`);

    const headerRlp = rawHeaderHex ? hexToBuf(rawHeaderHex) : buildHeaderRlpFromBlock(block);
    console.log(`   Header RLP:  ${headerRlp.length} bytes\n`);

    // 6. Build the 5-item RLP payload.
    console.log("6. Building RLP payload...");
    const validators = headerValidators(headerRlp);
    console.log(`   Header lists ${validators.length} validators`);

    // [1] accountProof = [node0, node1, ...]
    const accountProof = proof.accountProof.map((h) => hexToBuf(h));

    // [2] storageProof = [ [key, [proofNode0, ...]], ... ]
    // No value field: ClprEvmStateProof.verifyProvenSlots reads each slot's value
    // from the Merkle proof leaf, so carrying it here would be redundant data.
    const storageProof = proof.storageProof.map((sp) => [
      hexToBuf(sp.key),
      sp.proof.map((h) => hexToBuf(h)),
    ]);

    // [3] bundleContent protobuf
    const msg1PayloadBuf = hexToBuf(provisioned.MSG1_PAYLOAD);
    const BUNDLE_CONTENT_BYTES = Buffer.concat([
      Buffer.from([0x12, msg1PayloadBuf.length]),
      msg1PayloadBuf,
    ]);

    // Top-level 5-item list: [currentHeader, [trustedSet, hops[]], accountProof, storageProof, bundleContent]
    const topLevelPayload = rlpEncode([
      rlpDecode(headerRlp), // 0: current block header (raw RLP list spliced as a nested list)
      [validators, []],     // 1: the trusted set (must hash to the anchor) and no hops (no rotation)
      accountProof,         // 2: account proof
      storageProof,         // 3: storage proof
      BUNDLE_CONTENT_BYTES, // 4: bundle content
    ]);

    console.log(`   Total payload: ${topLevelPayload.length} bytes\n`);

    // 7. Write outputs.
    console.log("7. Writing fixture files...");
    writeFileSync(join(FIXTURES_DIR, "bundlePayload.hex"), topLevelPayload.toString("hex") + "\n");
    console.log("   Written bundlePayload.hex");

    const anchorBlock = BigInt(proofBlock) - 1n;
    const anchorHeaderRlp = hexToBuf(await rpc("debug_getRawHeader", ["0x" + anchorBlock.toString(16)]));
    const trustAnchor = buildTrustAnchor(headerValidators(anchorHeaderRlp), hexToBuf(proof.codeHash), anchorBlock);
    writeFileSync(join(FIXTURES_DIR, "trustAnchor.hex"), trustAnchor.toString("hex") + "\n");
    console.log("   Written trustAnchor.hex");

    // ChannelContext: channelId (32 bytes) || remoteServiceAddress (20 bytes), matching
    // ClprTypes.encodeChannelContext.
    const channelContextBytes = Buffer.concat([hexToBuf(channelId), hexToBuf(contractAddress)]);
    writeFileSync(join(FIXTURES_DIR, "channelContext.hex"), channelContextBytes.toString("hex") + "\n");
    console.log("   Written channelContext.hex");

    const metadata = {
      generatedAt: new Date().toISOString(),
      validators: validators.map((v) => "0x" + v.toString("hex")),
      anchorBlockNumber: "0x" + anchorBlock.toString(16),
      deployer: provisioned.DEPLOYER,
      contractAddress,
      qbftVerifier: verifierAddr,
      channelId,
      peerSigner: provisioned.PEER_SIGNER,
      codeHash: proof.codeHash,
      storageHash: proof.storageHash,
      proofBlockNumber: proofBlock,
      blockHash: block.hash,
      stateRoot: block.stateRoot,
      channelsSlot: CHANNELS_SLOT,
      provenStructOffsets: PROVEN_STRUCT_OFFSETS.map((o) => Number(o)),
      storageKeys,
      slotValues: proof.storageProof.map((sp) => sp.value),
      bundleContentHex: BUNDLE_CONTENT_BYTES.toString("hex"),
      accountProofNodes: proof.accountProof.length,
      storageProofEntries: proof.storageProof.length,
    };
    writeFileSync(join(FIXTURES_DIR, "metadata.json"), JSON.stringify(metadata, null, 2) + "\n");
    console.log("   Written metadata.json");

    writeFileSync(
      join(FIXTURES_DIR, "debug-proof-data.json"),
      JSON.stringify(
        {
          rawHeaderHex: headerRlp.toString("hex"),
          block: {
            hash: block.hash,
            stateRoot: block.stateRoot,
            number: block.number,
            extraData: block.extraData,
          },
          account: {
            nonce: proof.nonce,
            balance: proof.balance,
            storageHash: proof.storageHash,
            codeHash: proof.codeHash,
          },
          accountProof: proof.accountProof,
          storageProof: proof.storageProof.map((sp) => ({
            key: sp.key,
            value: sp.value,
            proof: sp.proof,
          })),
        },
        null,
        2
      ) + "\n"
    );
    console.log("   Written debug-proof-data.json");

    // 7b. Regenerate the FINAL configProof.hex with the real service address and codeHash.
    //     The bootstrap configProof written in step 1b has zeros there; the bundle's account
    //     proof targets the real service, so the anchor must pin its codeHash. The header is
    //     the block before the bundle block (see trustAnchor.hex above).
    console.log("\n7b. Regenerating final configProof.hex...");
    const serviceAddress = hexToBuf(contractAddress);
    const finalConfigProof = buildConfigProof(anchorHeaderRlp, serviceAddress, hexToBuf(proof.codeHash));
    writeFileSync(join(FIXTURES_DIR, "configProof.hex"), finalConfigProof.toString("hex") + "\n");
    writeFileSync(join(FIXTURES_DIR, "serviceAddress.hex"), serviceAddress.toString("hex") + "\n");
    console.log(`   Written final configProof.hex (${finalConfigProof.length} bytes, replaces bootstrap)`);
    console.log("   Written serviceAddress.hex");

    // 8. Rotation fixture: vote validator #2 out (3 -> 2 members) and prove the SAME channel state
    //    at a block sealed by the new set. The bundle carries the change block as one hop, so the
    //    header-mode verifier must walk from the anchored 3-member set to the 2-member set.
    //    The hop is the first header whose validators[] lists the new set.
    console.log("\n8. Rotating the validator set (voting node2 out)...");
    // `validators` is sorted ascending, so [0] is 0x3C44… (anvil #2, node2). The integration test
    // hard-codes the surviving pair as anvil #0 and #1; keep this choice in step with it.
    const removed = validators[0];
    const removedHex = "0x" + removed.toString("hex");
    // A vote counts only from a validator; a majority of the 3 (node0 + node1) is enough.
    for (const url of NODE_RPCS.slice(0, 2)) {
      await rpcAt(url, "qbft_proposeValidatorVote", [removedHex, false]);
    }
    console.log(`   Proposed removal of ${removedHex} on node0 and node1`);

    // Wait until the chain head lists 2 validators, then locate the change block.
    const rotationStart = Date.now();
    let changeBlock = null;
    while (Date.now() - rotationStart < 120_000) {
      const head = BigInt(await rpc("eth_blockNumber"));
      const headHdr = hexToBuf(await rpc("debug_getRawHeader", ["0x" + head.toString(16)]));
      if (headerValidators(headHdr).length === validators.length - 1) {
        // Walk back to the first block that lists the new set.
        let n = head;
        while (n > BigInt(proofBlock)) {
          const prev = hexToBuf(await rpc("debug_getRawHeader", ["0x" + (n - 1n).toString(16)]));
          if (headerValidators(prev).length !== validators.length - 1) break;
          n -= 1n;
        }
        changeBlock = n;
        break;
      }
      await new Promise((r) => setTimeout(r, 1000));
    }
    if (changeBlock === null) throw new Error("validator removal did not take effect within 120s");
    console.log(`   Change block: ${changeBlock} (first header listing ${validators.length - 1} validators)`);

    // Prove at a block after the change block, sealed by the new set alone.
    let rotationProofBlock = changeBlock + 2n;
    while (BigInt(await rpc("eth_blockNumber")) < rotationProofBlock) {
      await new Promise((r) => setTimeout(r, 1000));
    }
    const rotationProofBlockHex = "0x" + rotationProofBlock.toString(16);
    const changeHeaderRlp = hexToBuf(await rpc("debug_getRawHeader", ["0x" + changeBlock.toString(16)]));
    const rotationHeaderRlp = hexToBuf(await rpc("debug_getRawHeader", [rotationProofBlockHex]));
    const rotationProof = await rpc("eth_getProof", [contractAddress, storageKeys, rotationProofBlockHex]);
    const newValidators = headerValidators(rotationHeaderRlp);
    console.log(`   Rotation proof block: ${rotationProofBlock}, header lists ${newValidators.length} validators`);
    if (rotationProof.storageHash !== proof.storageHash) {
      throw new Error("channel storage changed between the two proof blocks; rotation fixture would not match");
    }

    const rotationPayload = rlpEncode([
      rlpDecode(rotationHeaderRlp),                 // 0: current header, sealed by the 2-member set
      [validators, [rlpDecode(changeHeaderRlp)]],   // 1: anchored 3-member set + one hop (the change block)
      rotationProof.accountProof.map((h) => hexToBuf(h)),
      rotationProof.storageProof.map((sp) => [hexToBuf(sp.key), sp.proof.map((h) => hexToBuf(h))]),
      BUNDLE_CONTENT_BYTES,                         // same message, same channel state
    ]);
    writeFileSync(join(FIXTURES_DIR, "bundlePayload.rotation.hex"), rotationPayload.toString("hex") + "\n");
    console.log(`   Written bundlePayload.rotation.hex (${rotationPayload.length} bytes)`);

    metadata.rotation = {
      removedValidator: removedHex,
      validatorsAfter: newValidators.map((v) => "0x" + v.toString("hex")),
      changeBlockNumber: "0x" + changeBlock.toString(16),
      proofBlockNumber: rotationProofBlockHex,
    };
    writeFileSync(join(FIXTURES_DIR, "metadata.json"), JSON.stringify(metadata, null, 2) + "\n");
    console.log("   Updated metadata.json with the rotation details");

    console.log("\n=== Done! ===");
    console.log(`\nFixture directory: ${FIXTURES_DIR}`);
    console.log("  bundlePayload.hex      — RLP([header, [trustedSet, hops], accountProof, storageProof, bundleContent])");
  console.log("  bundlePayload.rotation.hex — same channel state after a 3 -> 2 validator rotation, with the change block as a hop");
    console.log("  configProof.hex        — RLP([serviceAddr, chainId, nanos, throttles, descriptor, header])");
    console.log("  trustAnchor.hex        — abi.encode(uint8 0, bytes32 setCommitment, bytes32 codeHash, uint64 anchorBlock)");
    console.log("  channelContext.hex     — channelId32 || serviceAddr20 (ClprTypes.encodeChannelContext); pass as verifyBundle's 3rd arg");
    console.log("  serviceAddress.hex     — 20-byte service address (raw)");
    console.log("  metadata.json          — channelId, derived keys, slot values, etc.");
    console.log("  debug-proof-data.json  — raw JSON-RPC dump for debugging");

  } finally {
    console.log("\n8. Stopping Besu cluster...");
    try { execSync("docker compose down -v", { cwd: __dirname, stdio: "pipe" }); } catch { }
  }
}

